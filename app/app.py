@st.cache_resource
def load_models():
    models = {}
    try:
        models["logreg"] = joblib.load(os.path.join(PROJECT_ROOT, "models", "baseline_logreg.pkl"))
    except Exception as e:
        models["logreg"] = None
        st.session_state.setdefault("load_errors", []).append(f"Logistic Regression: {e}")

    try:
        models["gbt"] = joblib.load(os.path.join(PROJECT_ROOT, "models", "baseline_gbt.pkl"))
    except Exception as e:
        models["gbt"] = None

    tfidf_dir = os.path.join(PROJECT_ROOT, "text_model", "saved_model")
    for key, filename in [
        ("tfidf_original", "tfidf_phishing_model.joblib"),
        ("tfidf_hardened", "tfidf_hardened_model.joblib"),
        ("tfidf_adv_trained", "tfidf_adversarially_trained_model.joblib"),
    ]:
        try:
            models[key] = joblib.load(os.path.join(tfidf_dir, filename))
        except Exception:
            models[key] = None

    return models


models = load_models()


