@app.get("/api/status")
def status():
    return {
        "llm_configured": llm_configured(),
        "models_loaded": {k: (v is not None) for k, v in MODELS.items()},
    }


class ScanRequest(BaseModel):
    url: str


@app.post("/api/scan")
def scan(req: ScanRequest):
    url = req.url.strip()
    _, feature_dict = features_as_row(url)

    # CHANGED: fixed URL classifier (facts-grounded prompt, strict parser, allowlist). verdict is PHISH | SAFE | UNSURE.
    llm_result = llm_classify_url(url)
    llm_label = llm_result["verdict"] if llm_result["verdict"] in ("PHISH", "SAFE") else None   # UNSURE -> null, show as "unsure" in the UI

    return {
        "url": url,
        "baseline": _baseline_predict(url),
        "tfidf": _tfidf_predict(url),
        "llm": {
            "label": llm_label,
            "raw": llm_result["verdict"],
            "confidence": llm_result["confidence"],
            "reason": llm_result["reason"],
            "source": llm_result["source"],
        },
        "llm_offline_mode": not llm_configured(),
        "features": feature_dict,
    }


class EvadeRequest(BaseModel):
    url: str
    attack: str


@app.post("/api/evade")
def evade(req: EvadeRequest):
    attack_fn = EVASION_ATTACKS.get(req.attack)
    if attack_fn is None:
        return {"error": f"Unknown attack '{req.attack}'. Options: {list(EVASION_ATTACKS.keys())}"}

    attacked_url = attack_fn(req.url)

    return {
        "original_url": req.url,
        "attacked_url": attacked_url,
        "attack_label": EVASION_LABELS.get(req.attack, req.attack),
        "diff": describe_changes(req.url, attacked_url),
        "punycode_host": to_punycode_host(attacked_url) if attacked_url != req.url else None,
        "unchanged": attacked_url == req.url,
        "baseline_before": _baseline_predict(req.url),
        "baseline_after": _baseline_predict(attacked_url),
        "tfidf_before": _tfidf_predict(req.url),
        "tfidf_after": _tfidf_predict(attacked_url),
    }


@app.get("/api/evade/attacks")
def evade_attacks():
    return [{"id": k, "label": v} for k, v in EVASION_LABELS.items()]


class InjectRequest(BaseModel):
    message: str
    attack: str


@app.post("/api/inject")
def inject(req: InjectRequest):
    payloads = make_injection_payloads(req.message)
    payload = payloads.get(req.attack)
    if payload is None:
        return {"error": f"Unknown attack '{req.attack}'. Options: {list(payloads.keys())}"}

    # unchanged: the naive classifier is the red-team baseline. It now returns PHISH | SAFE | UNPARSEABLE | "ERROR: ..."
    # (before, an empty reply was silently reported as PHISH, so attacks always looked like they failed)
    undefended_result = llm_classify(payload)

    # Reference: what the naive classifier says about the CLEAN message (no injection).
    # An injection can only "succeed" if the clean message was caught as PHISH in the first place.
    clean_result = llm_classify(req.message)
    base_is_phish = clean_result == "PHISH"

    cleaned = sanitize(payload)
    hardened_prompt = build_hardened_prompt(cleaned)
    defended_result = llm_classify(hardened_prompt)

    return {
        "attack_label": INJECTION_LABELS.get(req.attack, req.attack),
        "payload": payload,
        "payload_visible": make_visible(payload),
        "base_message": req.message,
        "injected_part": injected_part(req.message, payload),
        "injected_part_visible": make_visible(injected_part(req.message, payload)),
        "hidden_instruction": INJECTION_INSTRUCTION,
        "explanation": ATTACK_INFO.get(req.attack, {}),
        "sanitized_payload": cleaned,
        "sanitizer_changed_payload": cleaned != payload,
        "hardened_prompt": hardened_prompt,
        "clean_label": clean_result,
        "base_is_phish": base_is_phish,
        "undefended": {
            "label": undefended_result,
            "attack_succeeded": base_is_phish and undefended_result == "SAFE",
        },
        "defended": {
            "label": defended_result,
            "attack_succeeded": base_is_phish and defended_result == "SAFE",
        },
        "llm_offline_mode": not llm_configured(),
    }


@app.get("/api/inject/attacks")
def inject_attacks():
    return [{"id": k, "label": v} for k, v in INJECTION_LABELS.items()]


@app.get("/api/results")
def results():
    out = {}

    summary_path = os.path.join(results_dir, "adversarial_summary.csv")
    if os.path.exists(summary_path):
        out["adversarial_summary"] = pd.read_csv(summary_path).to_dict(orient="records")

    before_path = os.path.join(PROJECT_ROOT, "attacks", "injection_results_before_defense.csv")
    after_path = os.path.join(PROJECT_ROOT, "attacks", "injection_results_after_defense.csv")
    if os.path.exists(before_path) and os.path.exists(after_path):
        before_df = pd.read_csv(before_path)
        after_df = pd.read_csv(after_path)
        merged = before_df.merge(after_df, on="attack", suffixes=("_before", "_after"))
        out["injection_results"] = merged.to_dict(orient="records")

    images = []
    for fname in [
        "robustness_comparison.png",
        "tf-idf_original_model_confusion_matrix.png",
        "tf-idf_hardened_model_confusion_matrix.png",
    ]:
        if os.path.exists(os.path.join(results_dir, fname)):
            images.append({"name": fname, "url": f"/static/{fname}"})
    out["images"] = images

    return out


