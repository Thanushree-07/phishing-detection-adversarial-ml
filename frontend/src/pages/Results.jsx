import { useEffect, useState } from "react";
import { api, STATIC_BASE_URL } from "../api/client";

export default function Results() {
  const [data, setData] = useState(null);
  const [error, setError] = useState(null);

  useEffect(() => {
    api.results().then(setData).catch(() => setError("Could not reach the backend."));
  }, []);

  if (error) {
    return (
      <div className="border border-danger/40 bg-danger/5 text-danger text-sm rounded-sm px-4 py-3 font-mono max-w-xl">
        {error}
      </div>
    );
  }

  if (!data) {
    return <div className="text-text-muted text-sm">Loading...</div>;
  }

  const hasSummary = data.adversarial_summary && data.adversarial_summary.length > 0;
  const hasInjection = data.injection_results && data.injection_results.length > 0;
  const hasImages = data.images && data.images.length > 0;

  return (
    <div className="max-w-5xl space-y-12">
      <div>
        <h1 className="text-2xl font-semibold mb-1">Project results</h1>
        <p className="text-text-muted text-sm max-w-xl">
          Results already generated by the team's training and attack scripts.
        </p>
      </div>

      <section>
        <h2 className="text-sm font-medium mb-3">
          TF-IDF model — adversarial robustness
        </h2>
        {hasSummary ? (
          <div className="border border-border rounded-sm overflow-hidden mb-6">
            <table className="w-full text-sm font-mono">
              <thead>
                <tr className="bg-panel2 text-text-faint text-xs">
                  <th className="text-left px-4 py-2.5 font-medium">model</th>
                  <th className="text-left px-4 py-2.5 font-medium">attack</th>
                  <th className="text-left px-4 py-2.5 font-medium">success rate</th>
                  <th className="text-left px-4 py-2.5 font-medium">detection rate</th>
                </tr>
              </thead>
              <tbody>
                {data.adversarial_summary.map((row, i) => (
                  <tr key={i} className={i % 2 === 0 ? "bg-panel" : "bg-panel2"}>
                    <td className="px-4 py-2 text-text-primary">{row.model}</td>
                    <td className="px-4 py-2 text-text-muted">{row.attack}</td>
                    <td className="px-4 py-2 text-danger">
                      {(row.attack_success_rate * 100).toFixed(1)}%
                    </td>
                    <td className="px-4 py-2 text-safe">
                      {(row.detection_rate * 100).toFixed(1)}%
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        ) : (
          <p className="text-text-faint text-sm font-mono">no adversarial_summary.csv found yet</p>
        )}

        {hasImages && (
          <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
            {data.images.map((img) => (
              <div key={img.name} className="border border-border rounded-sm overflow-hidden bg-panel">
                <img
                  src={`${STATIC_BASE_URL}${img.url}`}
                  alt={img.name}
                  className="w-full"
                />
                <div className="px-3 py-2 text-xs font-mono text-text-faint border-t border-border">
                  {img.name}
                </div>
              </div>
            ))}
          </div>
        )}
      </section>

      <section>
        <h2 className="text-sm font-medium mb-3">Prompt injection results</h2>
        {hasInjection ? (
          <div className="border border-border rounded-sm overflow-hidden">
            <table className="w-full text-sm font-mono">
              <thead>
                <tr className="bg-panel2 text-text-faint text-xs">
                  <th className="text-left px-4 py-2.5 font-medium">attack</th>
                  <th className="text-left px-4 py-2.5 font-medium">before defense</th>
                  <th className="text-left px-4 py-2.5 font-medium">after defense</th>
                </tr>
              </thead>
              <tbody>
                {data.injection_results.map((row, i) => (
                  <tr key={i} className={i % 2 === 0 ? "bg-panel" : "bg-panel2"}>
                    <td className="px-4 py-2 text-text-primary">{row.attack}</td>
                    <td className={`px-4 py-2 ${row.attack_succeeded_before ? "text-danger" : "text-safe"}`}>
                      {String(row.attack_succeeded_before)}
                    </td>
                    <td className={`px-4 py-2 ${row.attack_succeeded_after ? "text-danger" : "text-safe"}`}>
                      {String(row.attack_succeeded_after)}
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        ) : (
          <p className="text-text-faint text-sm font-mono">
            run attacks/run_injection_attacks.py and attacks/run_defended_attacks.py to populate this
          </p>
        )}
      </section>
    </div>
  );
}
