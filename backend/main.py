def _safe_load(path):
    try:
        return joblib.load(path)
    except Exception:
        return None


MODELS = {
    "logreg": _safe_load(os.path.join(PROJECT_ROOT, "models", "baseline_logreg.pkl")),
    "gbt": _safe_load(os.path.join(PROJECT_ROOT, "models", "baseline_gbt.pkl")),
    "tfidf_original": _safe_load(os.path.join(PROJECT_ROOT, "text_model", "saved_model", "tfidf_phishing_model.joblib")),
    "tfidf_hardened": _safe_load(os.path.join(PROJECT_ROOT, "text_model", "saved_model", "tfidf_hardened_model.joblib")),
    "tfidf_adv_trained": _safe_load(os.path.join(PROJECT_ROOT, "text_model", "saved_model", "tfidf_adversarially_trained_model.joblib")),
}


def _baseline_predict(url):
    model = MODELS.get("gbt")
    if model is None:
        return None
    row, _ = features_as_row(url)
    df = pd.DataFrame([row], columns=FEATURE_ORDER)
    pred = int(model.predict(df)[0])
    prob = float(model.predict_proba(df)[0][1])
    return {"label": "PHISH" if pred == 1 else "SAFE", "phishing_probability": round(prob, 4)}


def _tfidf_predict(url, which="tfidf_original"):
    model = MODELS.get(which)
    if model is None:
        return None
    pred = int(model.predict([url])[0])
    prob = float(model.predict_proba([url])[0][1])
    return {"label": "PHISH" if pred == 1 else "SAFE", "phishing_probability": round(prob, 4)}


